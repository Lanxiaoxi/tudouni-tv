    /**
     * 根据已输入的拼音串返回候选词（全拼前缀或首字母前缀匹配，最多 MAX 个）。
     * 输入为空或含非字母字符时返回空。
     */
    fun matchCandidates(input: String, max: Int = 16): List<String> {
        val q = input.trim().lowercase()
        if (q.isEmpty() || q.any { it < 'a' || it > 'z' }) return emptyList()
        val result = ArrayList<String>(max)
        for (e in entries) {
            if (result.size >= max) break
            if (e.pinyin.startsWith(q) || e.initials.startsWith(q)) result.add(e.word)
        }
        return result
    }
